"""
monitoring/latency_monitor.py

Phase 2 module.

Low-level, cross-platform ICMP ping runner used by both gateway_monitor.py
and internet_monitor.py. Centralizing this here means the OS-specific
command line and output parsing only has to be written once.

Design choice: we shell out to the platform's own `ping` executable
(subprocess) rather than using the `ping3` library. `ping3` sends raw
ICMP sockets, which requires Administrator/root privileges (or a setuid
binary) on most systems; the system `ping` command already carries the
necessary privilege on both Windows and Linux without any extra setup,
which fits the project's "should work without requiring cloud services"
/ low-friction requirement. The project spec explicitly allows either
approach ("ping3 or subprocess ping").

For low overhead, a single ping invocation can request multiple packets
at once (`-c N` / `-n N`), which is used by internet_monitor.py to get
latency, packet loss AND jitter from one subprocess call instead of N
separate ones.
"""

from __future__ import annotations

import platform
import re
import subprocess
import time
from dataclasses import dataclass, field
from typing import List

from utils.logger import get_logger

logger = get_logger(__name__)

_IS_WINDOWS = platform.system().lower() == "windows"

# Regex for an individual round-trip time inside ping output.
# Linux/macOS: "time=23.4 ms"   Windows: "time=23ms" or "time<1ms"
_TIME_PATTERN = re.compile(r"time[=<]\s*([\d.]+)\s*ms", re.IGNORECASE)

# Regex for the summary line's packet counts.
# Linux:   "4 packets transmitted, 3 received, 25% packet loss, time 3005ms"
_LINUX_SUMMARY_PATTERN = re.compile(
    r"(\d+)\s+packets transmitted,\s*(\d+)\s+received", re.IGNORECASE
)
# Windows: "Packets: Sent = 4, Received = 3, Lost = 1 (25% loss),"
_WINDOWS_SUMMARY_PATTERN = re.compile(
    r"Sent\s*=\s*(\d+),\s*Received\s*=\s*(\d+)", re.IGNORECASE
)


@dataclass
class RawPingResult:
    """Everything measurable from one ping invocation (which may send
    several ICMP packets)."""

    reachable: bool = False
    packets_sent: int = 0
    packets_received: int = 0
    samples_ms: List[float] = field(default_factory=list)
    error: str = ""
    duration_seconds: float = 0.0

    @property
    def packet_loss_percent(self) -> float:
        if self.packets_sent <= 0:
            return 100.0
        lost = self.packets_sent - self.packets_received
        return round((lost / self.packets_sent) * 100.0, 2)

    @property
    def average_latency_ms(self):
        if not self.samples_ms:
            return None
        return round(sum(self.samples_ms) / len(self.samples_ms), 2)

    @property
    def min_latency_ms(self):
        if not self.samples_ms:
            return None
        return round(min(self.samples_ms), 2)

    @property
    def max_latency_ms(self):
        if not self.samples_ms:
            return None
        return round(max(self.samples_ms), 2)

    @property
    def estimated_bytes_used(self) -> int:
        """
        Rough estimate of network bytes generated by this ping call, used
        to feed the project's low-overhead "measurement overhead"
        calculation. A standard ICMP echo request/reply pair with default
        payload is ~64 bytes on the wire each way; we count both
        directions for every packet actually sent.
        """
        return self.packets_sent * 64 * 2


def _build_command(host: str, count: int, timeout_seconds: float) -> List[str]:
    if _IS_WINDOWS:
        # -n <count>: number of echo requests
        # -w <ms>: timeout per reply, in milliseconds
        timeout_ms = max(1, int(timeout_seconds * 1000))
        return ["ping", "-n", str(count), "-w", str(timeout_ms), host]

    # Linux/macOS: -c <count>, -W <seconds> (per-reply timeout on Linux;
    # macOS's ping uses -W in milliseconds, but this project targets
    # Windows primarily -- the Linux path exists for development/testing).
    timeout_s = max(1, int(round(timeout_seconds)))
    return ["ping", "-c", str(count), "-W", str(timeout_s), host]


def run_ping(host: str, count: int = 1, timeout_seconds: float = 2.0) -> RawPingResult:
    """
    Ping `host` `count` times in a single subprocess call and return a
    RawPingResult with every individual round-trip time found, plus the
    packet-loss count parsed from the summary line.

    Never raises: any failure (host unreachable, command missing,
    timeout) is reflected in the returned RawPingResult instead.
    """
    result = RawPingResult(packets_sent=count)
    command = _build_command(host, count, timeout_seconds)

    # Overall subprocess timeout: give every packet its allotted time
    # plus a little slack for process startup/teardown.
    overall_timeout = (timeout_seconds * count) + 3

    start = time.monotonic()
    try:
        completed = subprocess.run(
            command,
            capture_output=True,
            text=True,
            timeout=overall_timeout,
            check=False,
        )
        output = completed.stdout or ""

        result.samples_ms = [float(match) for match in _TIME_PATTERN.findall(output)]

        summary_pattern = _WINDOWS_SUMMARY_PATTERN if _IS_WINDOWS else _LINUX_SUMMARY_PATTERN
        summary_match = summary_pattern.search(output)
        if summary_match:
            sent = int(summary_match.group(1))
            received = int(summary_match.group(2))
            result.packets_sent = sent
            result.packets_received = received
        else:
            # No parseable summary (e.g. host resolution failed before any
            # packet was sent) -- treat as fully lost.
            result.packets_received = len(result.samples_ms)

        result.reachable = result.packets_received > 0

    except FileNotFoundError:
        result.error = "ping command not found on this system"
        logger.error(result.error)
    except subprocess.TimeoutExpired:
        result.error = f"ping to {host} timed out"
        logger.warning(result.error)
    except OSError as exc:
        result.error = f"OS error running ping: {exc}"
        logger.warning(result.error)

    result.duration_seconds = time.monotonic() - start
    return result


if __name__ == "__main__":
    for target in ("127.0.0.1", "8.8.8.8"):
        r = run_ping(target, count=3, timeout_seconds=2.0)
        print(target, "->", r)
